export const freeDeliveryBooks = books.filter(
  (book) => book.price >= 999 || book.tags.includes("free-delivery"),
);

export function getBook(slug: string): Book | undefined {
  return books.find((book) => book.slug === slug);
}

export function getBooksByCategory(category: string): Book[] {
  return books.filter((book) => book.category === category);
}

export function getBooksByAuthor(authorSlug: string): Book[] {
  return books.filter((book) => book.authorSlug === authorSlug);
}

export function getBooksByPublisher(publisherSlug: string): Book[] {
  return books.filter((book) => book.publisherSlug === publisherSlug);
}

export function getBooksByCollection(collection: CollectionSlug): Book[] {
  switch (collection) {
    case "bestseller":
      return books.filter((book) => book.tags.includes("bestseller"));
    case "new":
      return books.filter((book) => book.tags.includes("new"));
    case "viral":
      return books.filter((book) => book.tags.includes("viral"));
    case "international":
      return books.filter((book) => book.category === "international");
    case "student":
      return books.filter((book) => book.category === "student");
    case "audio":
      return books.filter((book) => Boolean(book.audio));
  }
}

export function relatedBooks(book: Book, count = 6): Book[] {
  const sameCategory = books.filter(
    (item) => item.slug !== book.slug && item.category === book.category,
  );
  const others = books.filter(
    (item) => item.slug !== book.slug && item.category !== book.category,
  );
  return [...sameCategory, ...others].slice(0, count);
}

